import heapq


def top_k(stream, k):
    """Вернуть k наибольших элементов из потока.

    Args:
        stream: итерируемая последовательность элементов.
        k: целое число, сколько наибольших элементов нужно вернуть.

    Returns:
        Список из не более чем k наибольших элементов, отсортированный
        по убыванию. Если k <= 0 — пустой список. Если элементов в stream
        меньше k — возвращаются все, отсортированные по убыванию.
    """
    # Граничный случай: если k <= 0, держать нечего.
    if k <= 0:
        return []

    # heap <- empty bounded heap of size k
    # Куча хранит не более k элементов. Это min-heap по значению,
    # поэтому на вершине всегда окажется «худший из лучших» —
    # наименьший среди текущих кандидатов.
    heap = []

    # for element in stream:
    for element in stream:
        # push(heap, element)
        # Пока куча не заполнена, просто добавляем элемент.
        if len(heap) < k:
            heapq.heappush(heap, element)
        # if size(heap) > k: pop(heap)   # evict worst of the best
        # Когда куча заполнена, сравниваем новый элемент с вершиной.
        # Если новый больше «худшего из лучших», вытесняем вершину.
        elif element > heap[0]:
            heapq.heapreplace(heap, element)

    # return heap
    # В куче лежат k наибольших, но в порядке min-heap.
    # Для наглядного результата сортируем по убыванию.
    return sorted(heap, reverse=True)
